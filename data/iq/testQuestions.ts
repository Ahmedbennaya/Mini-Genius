export const TEST_QUESTIONS: TestQuestion[] = SEEDS.map((seed, idx) => {
  const idNum = idx + 1;
  return {
    id: `q-${String(idNum).padStart(3, "0")}`,
    category: seed.cat,
    ageGroup: seed.age,
    difficulty: seed.diff,
    type: seed.type,
    question: seed.q,
    options: seed.options,
    correctAnswer: seed.correct,
    explanation: seed.exp,
    points: seed.points ?? 5,
    timeLimitSeconds: seed.time,
  };
});

export function listQuestions(): TestQuestion[] {
  return TEST_QUESTIONS;
}

export function questionsForAge(age: AgeGroup, count = 20): TestQuestion[] {
  const exact = TEST_QUESTIONS.filter((q) => q.ageGroup === age);
  if (exact.length >= count) return exact.slice(0, count);
  const others = TEST_QUESTIONS.filter((q) => q.ageGroup !== age);
  return [...exact, ...others].slice(0, count);
}

export function balancedQuestionSet(age: AgeGroup, count = 20): TestQuestion[] {
  const buckets = new Map<CategoryId, TestQuestion[]>();
  TEST_QUESTIONS.forEach((q) => {
    const arr = buckets.get(q.category) ?? [];
    arr.push(q);
    buckets.set(q.category, arr);
  });
  const ageMatching = (qs: TestQuestion[]) => qs.filter((q) => q.ageGroup === age);

  const result: TestQuestion[] = [];
  const cats = Array.from(buckets.keys());
  while (result.length < count) {
    let added = false;
    for (const cat of cats) {
      if (result.length >= count) break;
      const all = buckets.get(cat) ?? [];
      const matching = ageMatching(all).filter((q) => !result.includes(q));
      const fallback = all.filter((q) => !result.includes(q));
      const pick = matching[0] ?? fallback[0];
      if (pick) {
        result.push(pick);
        added = true;
      }
    }
    if (!added) break;
  }
  return result.slice(0, count);
}
